import Foundation

/// Result of running text through the redactor.
public struct RedactionOutput: Equatable {
    public let text: String
    /// Number of values replaced with `[REDACTED:kind]`.
    public let count: Int
    /// Kind of each replacement, in the order they were made (never the values).
    public let kinds: [String]
}

/// All secret handling lives here. Pure Foundation, no AppKit, so it can be
/// unit-tested without a GUI session.
///
/// Layers (mirrors the spec):
///  1. `isSensitiveField` – fields that must never be read at all.
///  2. `isConcealedPasteboard` – clipboard contents marked by password managers.
///  3. `isBlockedApp` – password managers / keychain: record app name only.
///  4. Regex rules in `redact` – known key formats, PEM, key=value, URL creds,
///     card numbers (Luhn), Swedish personnummer, one-time codes.
///  5. Entropy pass in `redact` – long random-looking tokens.
public enum Redactor {

    public static let marker = "[REDACTED:"

    // MARK: - Layer 1: sensitive fields

    public static let secureRoles: Set<String> = ["AXSecureTextField"]

    /// Matched as substrings (after camelCase is split into words).
    static let substringFieldWords = [
        "password", "passwd", "lösenord", "losenord", "passcode", "secret", "token",
        "säkerhetskod", "sakerhetskod", "pinkod", "engångskod", "engangskod",
    ]
    /// Short words matched only when not glued to other letters, so that
    /// "shipping" or "spinner" do not count as "pin".
    static let boundedFieldWords = ["pin", "otp", "2fa", "cvc", "cvv", "cvv2"]

    static let boundedFieldRegexes: [NSRegularExpression] = boundedFieldWords.map {
        try! NSRegularExpression(pattern: "(?<![\\p{L}])\($0)(?![\\p{L}])")
    }

    /// True if a label, placeholder, identifier or name suggests a secret.
    public static func isSensitiveFieldName(_ raw: String) -> Bool {
        guard !raw.isEmpty else { return false }
        let spaced = raw.replacingOccurrences(
            of: "(\\p{Ll})(\\p{Lu})", with: "$1 $2", options: .regularExpression
        ).lowercased()
        for w in substringFieldWords where spaced.contains(w) { return true }
        let ns = spaced as NSString
        let range = NSRange(location: 0, length: ns.length)
        for re in boundedFieldRegexes where re.firstMatch(in: spaced, range: range) != nil {
            return true
        }
        return false
    }

    /// Decide from role/subrole plus every name-ish attribute of a field.
    public static func isSensitiveField(role: String?, subrole: String?, names: [String?]) -> Bool {
        if let role, secureRoles.contains(role) { return true }
        if let subrole, secureRoles.contains(subrole) { return true }
        return names.contains { isSensitiveFieldName($0 ?? "") }
    }

    // MARK: - Layer 2: clipboard

    public static let concealedPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public static func isConcealedPasteboard(types: [String]) -> Bool {
        types.contains { concealedPasteboardTypes.contains($0) }
    }

    // MARK: - Layer 3: blocked apps

    public static let blockedBundleIDs: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4", "com.bitwarden.desktop", "com.dashlane.dashlanephonefinal",
        "com.dashlane.Dashlane", "com.apple.Passwords", "com.apple.keychainaccess",
        "com.apple.Passwords-Settings.extension",
    ]
    static let blockedNameWords = ["1password", "bitwarden", "dashlane", "keepass", "lastpass",
                                   "nordpass", "enpass", "keeper", "roboform", "strongbox",
                                   "proton pass", "keychain", "nyckelhanteraren", "gnome-keyring", "seahorse"]

    public static func isBlockedApp(bundleID: String?, name: String?) -> Bool {
        if let b = bundleID, blockedBundleIDs.contains(b) || b.lowercased().hasPrefix("com.1password") {
            return true
        }
        let n = (name ?? "").lowercased()
        if n == "lösenord" || n == "passwords" { return true }
        return blockedNameWords.contains { n.contains($0) }
    }

    // MARK: - Layer 4: regex rules

    typealias Validator = (_ value: String, _ match: NSRange, _ whole: NSString) -> Bool

    struct Rule {
        let kind: String
        let regex: NSRegularExpression
        /// Capture group to replace (0 = whole match).
        let group: Int
        let validate: Validator?

        init(_ kind: String, _ pattern: String, group: Int = 0,
             options: NSRegularExpression.Options = [], validate: Validator? = nil) {
            self.kind = kind
            self.regex = try! NSRegularExpression(pattern: pattern, options: options)
            self.group = group
            self.validate = validate
        }
    }

    /// Context that marks a nearby 4–8 digit number as a one-time code. Whole
    /// words only, plus listed compounds ("verifieringskod", "passcode"), so
    /// "codes", "Unicode", "barcode" or "kodning" do not count.
    static let otpContext = try! NSRegularExpression(
        pattern: "(?<![\\p{L}])(?:(?:verifierings|säkerhets|engångs|bekräftelse|inloggnings|login|pass|sms-?)?kod(?:en)?|(?:pass)?code|otp|bankid|2fa|verifi[\\p{L}]*|one-time)(?![\\p{L}])",
        options: [.caseInsensitive])
    /// Characters before / after the number that are searched for context.
    static let otpContextBefore = 30
    static let otpContextAfter = 12

    /// Order matters: most specific first, so a GitHub token is reported as
    /// github_token and not later as high_entropy.
    static let rules: [Rule] = [
        Rule("private_key",
             "-----BEGIN [A-Z0-9 ]*KEY-----[\\s\\S]*?-----END [A-Z0-9 ]*KEY-----"),
        Rule("api_key", "sk-ant-[A-Za-z0-9_\\-]{16,}"),
        // Stripe secret/restricted keys and webhook secrets, Linear, Hugging Face.
        Rule("api_key", "(?<![A-Za-z0-9])(?:sk|rk)_(?:live|test)_[A-Za-z0-9]{16,}"),
        Rule("webhook_secret", "(?<![A-Za-z0-9])whsec_[A-Za-z0-9+/=]{20,}"),
        Rule("api_key", "(?<![A-Za-z0-9])lin_api_[A-Za-z0-9]{30,}"),
        Rule("api_key", "(?<![A-Za-z0-9])hf_[A-Za-z0-9]{30,}"),
        Rule("api_key", "(?<![A-Za-z0-9_\\-])sk-(?:proj-|live-|test-)?[A-Za-z0-9_\\-]{20,}"),
        Rule("github_token",
             "(?<![A-Za-z0-9_])(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{22,})"),
        Rule("slack_token", "(?<![A-Za-z0-9])xox[abposr]-[A-Za-z0-9\\-]{10,}"),
        Rule("aws_key", "(?<![A-Z0-9])(?:AKIA|ASIA)[0-9A-Z]{16}(?![A-Z0-9])"),
        Rule("google_api_key", "(?<![A-Za-z0-9])AIza[0-9A-Za-z_\\-]{35}"),
        Rule("gitlab_token", "(?<![A-Za-z0-9])glpat-[A-Za-z0-9_\\-]{20,}"),
        Rule("npm_token", "(?<![A-Za-z0-9])npm_[A-Za-z0-9]{36,}"),
        Rule("jwt", "(?<![A-Za-z0-9_\\-])eyJ[A-Za-z0-9_\\-]{5,}\\.[A-Za-z0-9_\\-]{5,}\\.[A-Za-z0-9_\\-]{5,}"),
        Rule("bearer_token", "\\bBearer\\s+([A-Za-z0-9\\-._~+/]{16,}=*)", group: 1,
             options: [.caseInsensitive]),
        Rule("url_credentials", "\\b[a-z][a-z0-9+.\\-]*://([^\\s:/@\\[\\]]+:[^\\s/@\\[\\]]+)@", group: 1,
             options: [.caseInsensitive]),
        Rule("url_param",
             "[?&#;](?:token|key|api_key|apikey|sig|signature|code|access_token|refresh_token|id_token|password|pwd|passwd|secret|client_secret|auth)=([^&#\\s\"'<>]+)",
             group: 1, options: [.caseInsensitive]),
        Rule("secret",
             "(?<![\\p{L}\\p{N}])(?:password|passwd|pwd|lösenord|losenord|secret|token|api[_\\-]?key|apikey|access[_\\-]?key|client[_\\-]?secret|private[_\\-]?key|auth)(?:[_\\-][A-Za-z0-9_]*)?(?![\\p{L}\\p{N}])[\"']?\\s*[:=]\\s*[\"']?([^\\s\"',;\\[\\]\\{\\}]+)",
             group: 1, options: [.caseInsensitive]),
        Rule("personnummer", "(?<![\\d\\-])((?:19|20)?\\d{6}[\\-+]?\\d{4})(?!\\d)", group: 1,
             validate: { value, _, _ in Redactor.isPersonnummer(value) }),
        // Card numbers start with 2–6 (Visa, Mastercard, Amex, Discover...).
        // Long IDs inside URLs/URNs (preceded by : / = etc.) are left alone.
        Rule("card_number", "(?<![\\d:/=_.#\\p{L}])[2-6](?:[ \\-]?\\d){12,18}(?![\\d\\p{L}])",
             validate: { value, _, _ in
                 let digits = value.filter(\.isNumber)
                 return (13...19).contains(digits.count) && Redactor.luhn(digits)
             }),
        Rule("otp", "(?<![\\d\\p{L}])(?<!\\d[\\-:/.,])\\d{4,8}(?![\\d\\p{L}])(?![\\-:/.,]\\d)",
             validate: { value, range, whole in
                 // Leave plain years alone.
                 if value.count == 4, let y = Int(value), (1900...2099).contains(y) { return false }
                 let start = max(0, range.location - Redactor.otpContextBefore)
                 let end = min(whole.length, range.location + range.length + Redactor.otpContextAfter)
                 let ctx = whole.substring(with: NSRange(location: start, length: end - start))
                 return Redactor.matches(Redactor.otpContext, ctx)
             }),
    ]

    // MARK: - Layer 5: entropy

    /// Runs of 24+ characters, split at whitespace and at URL/URN/key-value
    /// separators so "urn:li:activity:<id>" or "a=b&c=d" are judged per part.
    static let entropyCandidate = try! NSRegularExpression(pattern: "[^\\s:=&?,;]{24,}")
    static let trimSet = CharacterSet(charactersIn: "\"'`()<>[]{},;.:!?")
    static let schemePrefix = try! NSRegularExpression(pattern: "^[A-Za-z][A-Za-z0-9+.\\-]*://")
    static let bareDomain = try! NSRegularExpression(pattern: "^(?:www\\.)?[a-z0-9\\-]+(?:\\.[a-z0-9\\-]+)*\\.[a-z]{2,}(?:[/?#].*)?$")
    static let email = try! NSRegularExpression(pattern: "^[^@\\s]+@[^@\\s]+\\.[A-Za-z]{2,}$")
    static let hexOnly = try! NSRegularExpression(pattern: "^[0-9a-fA-F]{7,128}$")
    /// URLs in running text. IDs in URL paths are not treated as secrets;
    /// secrets in URLs are caught by url_credentials / url_param above.
    static let urlInText = try! NSRegularExpression(
        pattern: "(?:\\b[a-z][a-z0-9+.\\-]*://|\\bwww\\.)[^\\s\"'<>]+", options: [.caseInsensitive])
    /// Object IDs like Stripe's cus_…, pi_…, cs_test_…, price_… . Known
    /// secret prefixes (sk_live_, whsec_, ghp_, …) are already replaced above.
    static let prefixedID = try! NSRegularExpression(pattern: "^[a-z]{2,10}(?:_[a-z]{2,8})?_[A-Za-z0-9]{8,}$")
    static let uuid = try! NSRegularExpression(
        pattern: "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")

    public static let entropyThreshold = 4.0

    public static func shannonEntropy(_ s: String) -> Double {
        guard !s.isEmpty else { return 0 }
        var counts: [Character: Int] = [:]
        for c in s { counts[c, default: 0] += 1 }
        let n = Double(s.count)
        return counts.values.reduce(0) { acc, v in
            let p = Double(v) / n
            return acc - p * log2(p)
        }
    }

    public static func matches(_ re: NSRegularExpression, _ s: String) -> Bool {
        re.firstMatch(in: s, range: NSRange(location: 0, length: (s as NSString).length)) != nil
    }

    /// True if `token` looks like a random secret rather than a word, URL, path or hash.
    public static func looksLikeHighEntropySecret(_ token: String) -> Bool {
        guard token.count >= 24, !token.contains(marker) else { return false }
        if matches(schemePrefix, token) || matches(bareDomain, token) || matches(email, token) { return false }
        if token.hasPrefix("/") || token.hasPrefix("~/") || token.hasPrefix("./") || token.hasPrefix("../") {
            return false
        }
        if matches(hexOnly, token) || matches(uuid, token) || matches(prefixedID, token) { return false }
        let letters = token.filter(\.isLetter).count
        let digits = token.filter(\.isNumber).count
        guard letters > 0, digits > 0 else { return false }
        guard shannonEntropy(token) > entropyThreshold else { return false }
        // CamelCase identifiers like "UIApplicationDidFinishLaunching2" also pass
        // the entropy bar. Random tokens switch character class often, or are
        // digit-heavy; identifiers do neither.
        let classSwitches = classSwitchRatio(token)
        let digitShare = Double(digits) / Double(token.count)
        return classSwitches >= 0.35 || digitShare >= 0.2
    }

    static func classSwitchRatio(_ s: String) -> Double {
        func cls(_ c: Character) -> Int {
            if c.isUppercase { return 0 }
            if c.isLowercase { return 1 }
            if c.isNumber { return 2 }
            return 3
        }
        let chars = Array(s)
        guard chars.count > 1 else { return 0 }
        var switches = 0
        for i in 1..<chars.count where cls(chars[i]) != cls(chars[i - 1]) { switches += 1 }
        return Double(switches) / Double(chars.count - 1)
    }

    // MARK: - Checks

    public static func luhn(_ digits: String) -> Bool {
        let ds = digits.compactMap { $0.wholeNumberValue }
        guard ds.count == digits.count, ds.count >= 2 else { return false }
        var sum = 0
        for (i, d) in ds.reversed().enumerated() {
            if i % 2 == 1 {
                let x = d * 2
                sum += x > 9 ? x - 9 : x
            } else {
                sum += d
            }
        }
        return sum % 10 == 0
    }

    /// Swedish personnummer / samordningsnummer: valid month, day (or day+60)
    /// and Luhn checksum over the last ten digits.
    public static func isPersonnummer(_ value: String) -> Bool {
        let digits = value.filter(\.isNumber)
        guard digits.count == 10 || digits.count == 12 else { return false }
        let ten = String(digits.suffix(10))
        let a = Array(ten).compactMap { $0.wholeNumberValue }
        let month = a[2] * 10 + a[3]
        let day = a[4] * 10 + a[5]
        guard (1...12).contains(month) else { return false }
        guard (1...31).contains(day) || (61...91).contains(day) else { return false }
        return luhn(ten)
    }

    // MARK: - Main entry

    public static func redact(_ input: String) -> RedactionOutput {
        guard !input.isEmpty else { return RedactionOutput(text: input, count: 0, kinds: []) }
        var text = input
        var kinds: [String] = []

        for rule in rules {
            let ns = text as NSString
            let found = rule.regex.matches(in: text, range: NSRange(location: 0, length: ns.length))
            if found.isEmpty { continue }
            let out = NSMutableString(string: ns)
            for m in found.reversed() {
                let r = m.range(at: rule.group)
                guard r.location != NSNotFound, r.length > 0 else { continue }
                let value = ns.substring(with: r)
                if value.hasPrefix(marker) { continue }
                if let v = rule.validate, !v(value, m.range, ns) { continue }
                out.replaceCharacters(in: r, with: "\(marker)\(rule.kind)]")
                kinds.append(rule.kind)
            }
            text = out as String
        }

        // Entropy pass on what is left.
        let ns = text as NSString
        let full = NSRange(location: 0, length: ns.length)
        let found = entropyCandidate.matches(in: text, range: full)
        if !found.isEmpty {
            let urls = urlInText.matches(in: text, range: full).map(\.range)
            let out = NSMutableString(string: ns)
            for m in found.reversed() {
                if urls.contains(where: { NSIntersectionRange($0, m.range).length > 0 }) { continue }
                let raw = ns.substring(with: m.range)
                if raw.contains(marker) { continue }
                // Trim punctuation around the token but keep exact offsets.
                let scalars = Array(raw.utf16)
                var lo = 0, hi = scalars.count
                func isTrim(_ u: UInt16) -> Bool {
                    guard let s = Unicode.Scalar(u) else { return false }
                    return trimSet.contains(s)
                }
                while lo < hi, isTrim(scalars[lo]) { lo += 1 }
                while hi > lo, isTrim(scalars[hi - 1]) { hi -= 1 }
                let tr = NSRange(location: m.range.location + lo, length: hi - lo)
                guard tr.length >= 24 else { continue }
                let token = ns.substring(with: tr)
                if looksLikeHighEntropySecret(token) {
                    out.replaceCharacters(in: tr, with: "\(marker)high_entropy]")
                    kinds.append("high_entropy")
                }
            }
            text = out as String
        }

        return RedactionOutput(text: text, count: kinds.count, kinds: kinds)
    }
}
